def build_head(rule):
    head = rule.get_rule_name()

    input_vars = rule.vars_to_string("input")

    local_vars = rule.build_local_vars() 
    local_vars_string = ", ".join(local_vars)
    
    gv_aux = get_field_vars(rule)
    if(len(gv_aux)> 0 ):
        gv = ", ".join(gv_aux)
    else:
        gv = ""

    ts = rule.build_transient_vars()
    ts_vars_string = ", ".join(ts)
        
    cv_aux = get_contract_vars(rule)
    if(len(cv_aux)>0):
        cv = ", ".join(cv_aux)
    else:
        cv = ""

    if (input_vars == ""):
            if(gv == ""):
                d_vars = ""
            else:
                d_vars = gv
    else:
        d_vars = input_vars
        if(gv != ""):
            d_vars = d_vars+", "+gv

    if d_vars == "" and local_vars_string != "":
        d_vars = local_vars_string
    elif d_vars != "" and local_vars_string != "":
        d_vars = d_vars+", "+local_vars_string

    if d_vars != "" and ts_vars_string != "":
        d_vars = d_vars+", "+ts_vars_string
    elif d_vars == "" and ts_vars_string != "":
        d_vars = ts_vars_string
        
    if d_vars != "" and cv != "":
        d_vars = d_vars+", "+cv
    elif d_vars == "" and cv != "":
        d_vars = cv
    
    return head+"("+d_vars+")=>"



def process_rule_saco(rule, function_block_map, functions_calldataload_blocks, test_cases_info):
    new_rule = ""
    head = build_head(rule)
    new_rule = new_rule+head+"\n"
    if rule.get_guard()!="":
        new_rule = new_rule+"\t"+rule.get_guard()+"\n"

    instr_aux = process_instructions(rule, function_block_map, functions_calldataload_blocks, test_cases_info)
    instr = list(filter(lambda x: x !="",instr_aux))
    for ins in instr:
        new_rule = new_rule+"\t"+ins+"\n"

    return new_rule
    

def get_contract_vars(rule):
    bc = rule.get_bc()
    new = list(map(lambda x: "l("+x+")",bc))
    return new

def get_field_vars(rule):
    names, numeric = rule.get_global_arg()

    if numeric != []:
        new_numeric = list(map(lambda x: "field(g"+x+")",numeric))
    else:
        new_numeric = []
        
    if names != []:
        new_names = list(map(lambda x: "field("+x+")",names))
    else:
        new_names = []
        
    new = new_names+new_numeric 

    return new

def transform_vars(var):
    
    if var.find("s(")!=-1: #stack variable
        new_var = var
    elif var.find("g(")!=-1: #field variable
        posEnd = var.find(")")
        if st_vars ==[]:
            new_var = "field(g"+var[2:posEnd]+")"
        else:
            new_var = "field("+var[2:posEnd]+")"
    elif var.find("l(")!=-1: #local variable
        new_var = var
    elif var != "": #contract variable
        new_var = "l("+var+")"
    else:
        new_var = ""
    return new_var

def call_instruction(instr):

    pos_head = instr.find("(",5) #It is a call. It starts with call(__(
    end = len(instr)-2
    variables = instr[pos_head+1:end].split(",")
    new_vars = list(map(lambda x: transform_vars(x.strip()),variables))
    new_vars_string = ", ".join(new_vars)

    new_instr = instr[:pos_head+1]+new_vars_string+"))"
    return new_instr
    
def process_instructions(rule, function_block_map, functions_calldataload_blocks, test_info):
    cont = rule.get_fresh_index()+1
    contract_vars = rule.get_bc()
    instructions = rule.get_instructions()
    new_instructions = []
    has_string_pattern = rule.get_string_getter()
    idx_loop = 0
    len_ins = len(instructions)

    test_cases_info = test_info[0]
    test_id = test_info[1]
    
    if test_cases_info != {} and test_cases_info != None:
        rule_id = rule.get_Id()
        candidates = [x for x in functions_calldataload_blocks.keys() if rule_id in functions_calldataload_blocks[x]]
        if len(candidates) == 1:
            call_function_block = function_block_map.get(candidates[0], None)
            if call_function_block != None:
                all_tests_info = test_cases_info.get(call_function_block[0],{}).get("test_cases",{})
                if(len(all_tests_info) <= test_id):
                    raise Exception("There are less tests than the id specified")

                test_info = all_tests_info[test_id]
                print(test_info)
                new_instructions+=test_info.get("concrete_values",[]) 
                new_instructions+=test_info.get("constraints_clpq",[])
                # print(new_instructions)

                # print("*********")
                # print(candidates)
                # print(test_cases_info)
                # print(rule_id)
                # raise Exception
            
    
    while(idx_loop<len_ins):
        instr = instructions[idx_loop]

        if idx_loop == 8 and has_string_pattern:
            new_instructions = compute_string_pattern(new_instructions)
            idx_loop = idx_loop+26
        elif instr.find("/")!=-1:
            idx_loop = check_mul_div_pattern(new_instructions,instructions,idx_loop)
        else:
            cont = process_single_instruction(instr,new_instructions,contract_vars,cont)
            idx_loop = idx_loop+1
            
    return new_instructions

            
