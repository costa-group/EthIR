# ---------------------------------------------------------------------------
# Branch pruning for test-driven runs.
#
# When a specific test case drives the RBR generation, its concrete calldata
# values are already injected into the generated rules above (see the
# "concrete_values"/"constraints_clpq" insertion in process_instructions).
# But costabs' solver (PUBS) computes upper bounds per predicate, bottom-up
# and independently of the caller's context, so a jump-style dispatch rule
# several calls downstream of the calldataload point (e.g. the guard chain
# behind a switch/assert) still gets handed every alternative clause, and
# PUBS maximizes over all of them even when the concrete test already makes
# one of them infeasible.
#
# This pass follows the same call chain a concrete execution of that test
# would take, propagates the known calldata values through the plain
# "lhs = rhs" assignments emitted for each rule, and drops whichever clause
# of a multi-clause (jump-style) rule is provably unreachable for this
# specific test - so PUBS has nothing left to maximize over at that choice
# point, without requiring any change on the PUBS/costabs side.
# ---------------------------------------------------------------------------

_GUARD_OPS = {
    "eq": operator.eq,
    "neq": operator.ne,
    "lt": operator.lt,
    "leq": operator.le,
    "gt": operator.gt,
    "geq": operator.ge,
}

_VAR_TOKEN_RE = re.compile(r"s\(\d+\)|l\([\w\d]+\)|field\([\w\d]+\)")
_ARITH_ALLOWED_RE = re.compile(r"^[\d\s\+\-\*/\(\)\.]+$")
_HEAD_RE = re.compile(r"^(\w+)\((.*)\)=>$")
_CALL_RE = re.compile(r"^call\((\w+)\((.*)\)\)$")


def _split_top_level_args(args_text):
    """Split 'a, f(b, c), d' into ['a', 'f(b, c)', 'd'], respecting nested
    parentheses so an argument that is itself a call isn't cut in half."""
    args, depth, current = [], 0, ""
    for ch in args_text:
        if ch == "," and depth == 0:
            args.append(current.strip())
            current = ""
            continue
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        current += ch
    if current.strip():
        args.append(current.strip())
    return args


def _safe_eval_arithmetic(expr):
    """Evaluate a purely numeric +,-,*,/ expression (no variables, no calls)
    without resorting to eval(). Returns None if expr isn't purely numeric
    or uses anything beyond the four basic operators."""
    if not _ARITH_ALLOWED_RE.match(expr):
        return None
    try:
        node = ast.parse(expr, mode="eval")
    except SyntaxError:
        return None

    def _eval(n):
        if isinstance(n, ast.Expression):
            return _eval(n.body)
        if isinstance(n, ast.Constant) and isinstance(n.value, (int, float)):
            return n.value
        if isinstance(n, ast.UnaryOp) and isinstance(n.op, ast.USub):
            return -_eval(n.operand)
        if isinstance(n, ast.BinOp):
            left, right = _eval(n.left), _eval(n.right)
            if isinstance(n.op, ast.Add):
                return left + right
            if isinstance(n.op, ast.Sub):
                return left - right
            if isinstance(n.op, ast.Mult):
                return left * right
            if isinstance(n.op, ast.Div):
                # EVM DIV is unsigned integer division, truncating, and
                # defined as 0 for division by zero (never raises).
                return 0 if right == 0 else left // right
        raise ValueError("unsupported expression: " + expr)

    try:
        return _eval(node)
    except Exception:
        return None


_UINT256_MOD = 2 ** 256


def _resolve_expr(expr, env):
    """Substitute every s(N)/l(name)/field(name) token in expr with its
    concrete value from env and evaluate it. Returns a number, or None if
    expr references at least one variable that isn't known yet.

    The result is reduced modulo 2**256: every RBR assignment corresponds to
    one EVM opcode operating on 256-bit words, so plain (unbounded) Python
    arithmetic would get e.g. a SUB that underflows, or an ADD that
    overflows, wrong relative to real EVM semantics - and a negative
    concrete_values literal (used to denote a value near 2**256, e.g.
    'newOwner == -1' for 2**256-1) needs this same reduction to mean what it
    was meant to mean.
    """
    expr = expr.strip()
    for token in sorted(set(_VAR_TOKEN_RE.findall(expr)), key=len, reverse=True):
        if token not in env:
            return None
        expr = expr.replace(token, "("+str(env[token])+")")
    value = _safe_eval_arithmetic(expr)
    if value is None:
        return None
    return value % _UINT256_MOD


def evaluate_guard_against_concrete_values(guard_text, env):
    """Evaluate a SACO guard predicate (e.g. 'leq(s(7), s(6))') against a
    dict mapping already-known stack/local variables (e.g. 's(6)', 'l(l0)')
    to their concrete numeric value.

    Returns True/False when both operands resolve to concrete numbers, or
    None when the guard can't be decided yet (some operand is still
    symbolic). This is a fresh implementation, independent of
    parser_test_cases._evaluate_against_concrete_values: that one matches
    constraints expressed over source-level identifiers (function params,
    state variables), while this one matches the RBR's own stack-slot and
    local-variable names, which only line up with the source-level ones at
    the exact block where a CALLDATALOAD happens.
    """
    match = re.match(r"^(\w+)\((.*)\)$", guard_text.strip())
    if match is None:
        return None
    op_name, args_text = match.groups()
    op = _GUARD_OPS.get(op_name)
    if op is None:
        return None

    args = _split_top_level_args(args_text)
    if len(args) != 2:
        return None

    left = _resolve_expr(args[0], env)
    right = _resolve_expr(args[1], env)
    if left is None or right is None:
        return None
    return bool(op(left, right))


def _parse_saco_rule(text, index):
    """Parse one rendered SACO rule (as produced by process_rule_saco) back
    into its structural pieces: name, formal params, guard (if any), plain
    assignments and the single outgoing call (if any)."""
    lines = [l for l in text.rstrip("\n").split("\n") if l.strip() != ""]
    if not lines:
        return None
    head_match = _HEAD_RE.match(lines[0].strip())
    if head_match is None:
        return None
    name, params_text = head_match.groups()
    params = _split_top_level_args(params_text)
    body = [l.strip() for l in lines[1:]]

    guard = None
    if body:
        first_call = re.match(r"^(\w+)\(", body[0])
        if first_call and first_call.group(1) in _GUARD_OPS:
            guard = body[0]
            body = body[1:]

    call_name, call_args = None, None
    assignments = []
    for line in body:
        call_match = _CALL_RE.match(line)
        if call_match:
            call_name, call_args_text = call_match.groups()
            call_args = _split_top_level_args(call_args_text)
            continue
        if line.startswith("nop(") or line.startswith("'$"):
            continue
        if "=" in line:
            lhs, rhs = line.split("=", 1)
            assignments.append((lhs.strip(), rhs.strip()))

    return dict(index=index, name=name, params=params, guard=guard,
                assignments=assignments, call_name=call_name, call_args=call_args)


def _reachable_names(entry_name, clauses_by_name):
    """Names reachable from entry_name by following every call, ignoring
    guards entirely (i.e. as if every clause were feasible). Used as a
    baseline to tell 'orphaned by this test's pruning' apart from 'was never
    part of this entry's call graph to begin with' (e.g. another function)."""
    seen = set()
    stack = [entry_name]
    while stack:
        name = stack.pop()
        if name in seen or name not in clauses_by_name:
            continue
        seen.add(name)
        for clause in clauses_by_name[name]:
            if clause["call_name"] is not None:
                stack.append(clause["call_name"])
    return seen


def _find_looping_names(clauses_by_name):
    """Predicate names that are part of a cycle in the call graph - i.e.
    genuinely called again, directly or through other predicates, while
    still 'inside' themselves (a Yul/assembly for-loop, typically).

    Pruning a clause commits to whatever the guard evaluates to the FIRST
    time that predicate is visited (propagate()'s 'visited' set is
    permanent), which is fine for straight-line code reached exactly once,
    but wrong for a predicate that's re-entered on every loop iteration with
    a different environment (e.g. the loop counter): the decision made for
    iteration 0 would get frozen and wrongly applied to every later
    iteration too. Names in a cycle are therefore never pruned at all,
    regardless of what concrete_values would otherwise decide.
    """
    edges = {}
    for name, clauses in clauses_by_name.items():
        edges[name] = {c["call_name"] for c in clauses if c["call_name"] is not None}

    looping = set()
    for start in edges:
        stack = list(edges.get(start, ()))
        seen = set()
        while stack:
            node = stack.pop()
            if node == start:
                looping.add(start)
                break
            if node in seen or node not in edges:
                continue
            seen.add(node)
            stack.extend(edges.get(node, ()))
    return looping


def _referenced_vars(expr):
    """The set of s(N)/l(name)/field(gN) tokens an expression mentions."""
    return set(_VAR_TOKEN_RE.findall(expr))


def _guard_args(guard_text):
    """Split a guard predicate 'op(left, right)' into (left, right), or
    (None, None) if it doesn't parse as one."""
    match = re.match(r"^(\w+)\((.*)\)$", guard_text.strip())
    if match is None:
        return None, None
    args = _split_top_level_args(match.group(2))
    if len(args) != 2:
        return None, None
    return args[0], args[1]


def prune_infeasible_rules(new_rules, entry_name, concrete_values):
    """Drop the SACO rules whose guard is provably False *because of* one
    specific test case's concrete calldata values (e.g. 'l(calldataload0) =
    1') - not because of some unrelated, generically-true constant already
    in the RBR (e.g. a loop counter's own 'i := 0' initialization, which
    makes its first bounds check decidable regardless of any test).

    Without the first part, a test-driven run still hands PUBS every
    alternative of every jump-style dispatch rule (e.g. both branches of a
    switch/assert chain), so its per-predicate, bottom-up cost computation
    maximizes over branches the concrete input can never take. Removing the
    infeasible clause here means there is nothing left to maximize over at
    that point.

    The taint check exists because that same propagation also resolves
    plenty of guards that have nothing to do with the test at all (constant
    folding that would be equally valid on the generic, test-less run) -
    pruning those here would make test-driven output diverge from generic
    output for reasons unrelated to the test, which is exactly what this is
    meant to avoid. A guard is only pruned when at least one of its two
    operands' value is tainted, i.e. depends (through some chain of plain
    assignments) on at least one of concrete_values - never on RBR-local
    constants alone.

    Predicates that are part of a cycle in the call graph (i.e. a real
    loop, re-entered on every iteration with a different environment) are
    never pruned at all, even when a guard looks tainted and decidable -
    see _find_looping_names for why freezing a decision made on one
    iteration is unsound for the others.

    Returns a new list (new_rules is not mutated). Rules that can't be
    parsed, or that aren't reached while propagating concrete_values (e.g.
    because they belong to an unrelated function, or the propagation hits a
    variable it can't resolve), are left untouched - this pass only ever
    removes a clause it can positively prove infeasible using the test's
    own values.
    """
    if not concrete_values:
        return new_rules

    parsed = [_parse_saco_rule(text, i) for i, text in enumerate(new_rules)]
    clauses_by_name = {}
    for p in parsed:
        if p is not None:
            clauses_by_name.setdefault(p["name"], []).append(p)

    looping_names = _find_looping_names(clauses_by_name)

    env0 = {}
    injected_pairs = set()
    for value in concrete_values:
        if "=" not in value:
            continue
        lhs, rhs = value.split("=", 1)
        lhs, rhs = lhs.strip(), rhs.strip()
        injected_pairs.add((lhs, rhs))
        resolved = _resolve_expr(rhs, {})
        if resolved is not None:
            env0[lhs] = resolved
    tainted0 = set(env0)

    to_remove = set()
    visited = set()

    def continue_clause(clause, env, tainted):
        local_env = dict(env)
        local_tainted = set(tainted)
        for lhs, rhs in clause["assignments"]:
            value = _resolve_expr(rhs, local_env)
            if value is not None:
                local_env[lhs] = value
                # lhs is tainted iff its new definition reads at least one
                # already-tainted variable - a pure-constant rhs (or one
                # built only from untainted locals) yields an untainted lhs,
                # even though the concrete value happens to be known.
                #
                # Exception: process_instructions injects concrete_values
                # verbatim as plain assignment lines (e.g.
                # "l(calldataload0) = -1") directly in whichever block
                # first needs them. Read literally, that rhs is a bare
                # constant referencing nothing, so the rule above would
                # untaint it right where it's introduced. Recognize these
                # exact (lhs, rhs) pairs as taint sources instead.
                if (lhs, rhs) in injected_pairs or (_referenced_vars(rhs) & local_tainted):
                    local_tainted.add(lhs)
                else:
                    local_tainted.discard(lhs)
            else:
                # The new value can't be resolved (e.g. it depends on
                # something not fixed by concrete_values, like
                # calldatasize) - drop any stale concrete value lhs held
                # from an earlier assignment, instead of silently keeping
                # it around as if it were still valid.
                local_env.pop(lhs, None)
                local_tainted.discard(lhs)
        if clause["call_name"] is None:
            return
        callee_clauses = clauses_by_name.get(clause["call_name"])
        if not callee_clauses:
            return
        callee_params = callee_clauses[0]["params"]
        callee_env = {}
        callee_tainted = set()
        for param, arg_expr in zip(callee_params, clause["call_args"] or []):
            value = _resolve_expr(arg_expr, local_env)
            if value is not None:
                callee_env[param] = value
                if _referenced_vars(arg_expr) & local_tainted:
                    callee_tainted.add(param)
        propagate(clause["call_name"], callee_env, callee_tainted)

    def propagate(name, env, tainted):
        if name in visited or name not in clauses_by_name:
            return
        visited.add(name)
        in_loop = name in looping_names
        for clause in clauses_by_name[name]:
            should_remove = False
            if not in_loop and clause["guard"] is not None:
                verdict = evaluate_guard_against_concrete_values(clause["guard"], env)
                if verdict is False:
                    left, right = _guard_args(clause["guard"])
                    guard_vars = _referenced_vars(left or "") | _referenced_vars(right or "")
                    if guard_vars & tainted:
                        should_remove = True
            if should_remove:
                to_remove.add(clause["index"])
            else:
                continue_clause(clause, env, tainted)

    propagate(entry_name, env0, tainted0)

    if not to_remove:
        return new_rules

    # Dropping an infeasible clause can leave its callee (and everything
    # only reachable through it, e.g. block104/block127/block302 in the
    # switch/assert example) with no surviving caller at all. Those orphaned
    # rules are still textually present in new_rules, and PUBS still folds
    # their cost in when computing the entry's upper bound (795 instead of
    # the true 708 for this test - verified against costabs_shell directly).
    #
    # 'visited' is exactly the set of names still reachable once infeasible
    # clauses are taken into account. But a name that was never part of
    # entry_name's call graph to begin with (e.g. it belongs to a different
    # function entirely) also never ends up in 'visited', and must NOT be
    # removed on that basis alone - only names that were reachable *before*
    # this test's pruning and became unreachable *because* of it should go.
    reachable_before = _reachable_names(entry_name, clauses_by_name)
    orphaned = reachable_before - visited

    def is_kept(i, p):
        if i in to_remove:
            return False
        if p is None:
            # Couldn't parse it - leave it untouched rather than risk
            # dropping something load-bearing we don't understand.
            return True
        return p["name"] not in orphaned

    return [text for i, (text, p) in enumerate(zip(new_rules, parsed)) if is_kept(i, p)]
